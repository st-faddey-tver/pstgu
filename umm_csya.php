Стоит еще раз подчеркнуть следующее настоящий курс не имеет своей целью детальное, чисто лингвистическое изучение церковнославянского языка. Он ориентирован главным образом на освоение главнейших понятий и механизмов (по преимуществу грамматических) церковнославянского языка, необходимых для грамотного чтения и непротиворечивого понимания богослужебных текстов.


Методические рекомендации

Методические рекомендации по изучению модуля и организации самостоятельной работы

Для успешного освоения курса необходимо правильно организовать время, отводимое на изучение церковнославянского языка.

Для этого рекомендуется придерживаться следующих правил.

1. Для наиболее полного изучения и понимания курса необходимо регулярно посещать богослужение. Это настолько важное условие освоения материала, что без него теоретические занятия абсолютно бессмысленны. Читая учебные пособия, можно лишь узнать некий минимум теоретической информации, участвуя же в богослужении, приходится вспоминать то, что было изучено, то есть применять знания.

Церковнославянский язык нельзя постичь только умом, он призван осмыслить, обогатить то, что уже является частью духовной жизни.

2. Курс, естественно, построен по принципу тематической преемственности. Поэтому нельзя нарушать последовательность частей.

3. Задания по курсу в целом соответствуют темам указанных учебных пособий (прежде всего иеромонаха Алипия (Гамановича), А.А. Плетневой, А.Г. Кравецкого, А.Г. Вигасиной)

И, разумеется, при подготовке необходимо прежде всего уметь ориентироваться в теоретическом материале.

4. В первую очередь нужно освоить основные сведения, которые содержатся во всех учебных пособиях по церковнославянскому языку.

5. При изучении церковнославянского языка следует ориентироваться на минимальный уровень требований по курсу, необходимый для успешной аттестации.

6. Затем – при первичном наличии твердых знаний и навыков – можно ознакомиться с дополнительной информацией, которая имеет либо широкую культорологическую, либо узко лингвистическую направленность.

7. Вместе с тем ответы на занятиях, зачете и т.п. должны представлять собой самостоятельное, осмысленное рассуждение, конспект на основе материалов темы, а не механическое переписывание из учебных пособий.

8. Поскольку целью курса церковнославянского языка является изучение его основных явлений и закономерностей функционирования, задания (обучающие и контрольные) также делятся на два типа.

Одни направлены на освоение необходимого минимума теоретического материала, другие – на его осмысление и практическое применение. Для первых вполне достаточно объема учебного пособия, для вторых – потребуется определенные эвристические способности.

Задания обоих типов представлены в учебном пособии Л.И. Маршевой (Маршева Л.И. Шестопсалмие: учебно-лингвистический анализ. М., 2003, 2005).

9. В ходе поэтапного освоения церковнославянского языка нужно ориентироваться на постепенное овладение пунктов памятки «Основые принципы чтения и перевода церковнославянского текста», представленной ниже.

10. При изучении курса в рамках вечерней формы обучения не следует ограничиваться прослушиванием лекций и работой на практических занятиях. Нужно самостоятельно повторять пройденный материал по учебному пособию, выполнять соответствующие задания контрольной работы, обнаруживать пробелы в знаниях и навыках, пытаться находить в церковнославянских текстах изученные языковые явления, обосновывая свой выбор.

11. В ходе самостоятельного изучения курса (при заочном обучении) рекомендуется следующий порядок работы:

·         Изучение соответствующего раздела учебного пособия

·         Проверка знаний по вопросам для самопроверки

·         Выполнение соответствующих упражнений из учебного пособия, а также заданий контрольной работы, относящихся к изученному разделу.

·         Попытка найти в церковнославянских текстах изученные языковые явления и обосновать свой выбор.

Основные принципы чтения и перевода церковнославянского текста

0. Это должен быть именно точный, подстрочный перевод, а не приблизительная интерпретация. Поэтому при переводе надо попытаться «остаться» в пределах слов, имеющихся в предложении, ничего не придумывая. И, конечно, с наиболее возможной скрупулезностью отразить грамматику церковнославянского языка.

1. Перевод должен быть максимально приближен к современному русскому языку.

Это может повлечь за собой прежде всего:

а) изменение порядка слов – особенно постановку определения после определяемого, главного слова;

б) замену предлогов;

в) замену падежей;

г) замену звательной формы на и.п.;

д) замену отдельных слов;

е) пропуск отдельных слов;

ж) синонимические замены.

2. Структура церковнославянского текста такова, что предложение тесно связано с контекстом (то есть с предыдущим и последующими предложениями). и это необходимо учитывать при переводе, последовательно и логично «связывая» и «увязывая» предложения.

3. В каждом предложении обязательно должно быть сказуемое.

4. В каждом предложении имеется подлежащее или подразумевается его наличие.

5. В церковнославянских предложениях зачастую при глаголах отсутствуют личные и лично-указательные местоимения, которые надо подставлять в русский перевод (1 л. я – мы; 2 л. ты – вы; 3л. он, оно, она – они).

6. В церковнославянском тексте частотны формы настоящего, будущего, прошедшего времен глагола áxòè, которые при переводе на русский в подавляющем большинстве случаев или опускаются вовсе, или заменяются словами это или являться.

7. Перечисленные формы глагола áxòè при этом помогают установить грамматическое лицо и число.

8. У глаголов, а также у причастий при переводе на русский язык должен быть тот же вид, что и в церковнославянском.

9. Следует правильно выбрать вариант для сочетания «частица äà + форма настоящего или будущего простого времени».

10. Внимательно надо относиться к переводу инфинитивов и конструкций с ними.

11. Многие формы кратких действительных причастий в церковнославянском языке переводятся на русский язык как деепричастия.

12. Нужно безошибочно определять в предложениях оборот «дательный самостоятельный», а также конструкции с двойными падежами.

13. Надо видеть в текстах одиночное отрицание.

14. Пристальное внимание необходимо уделять союзам и союзным словам, так как они зачастую имеют несколько возможных переводов, особенно Tæå – &æå – Ræå, &êw, Aùå.

15. Надо помнить, что слова Tæå – &æå – Ræå и их падежные формы являются относительными местоимениями. А значит, переводятся они на русских язык как который: rì1æå – которому, Uìæå – которым.

16. Следует различать слова 4áw (как правило, это причинный союз – ибо, так как, потому что) и 5áî (как правило, это слово имеет семантику заключения, обобщения – итак, поэтому).


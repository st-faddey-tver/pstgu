        <h1>Церковнославянский язык</h1>
        <h2>Введение</h2>
        <p>Курс предназначен для учащихся факультета дополнительного образования ПСТГУ и разработан в соответствии с концепцией программы «Теология». В курсе по возможности унифицировано содержание учебного материала очной, заочной и дистанционной форм обучения.</p>
        <p>«Церковнославянский язык» как учебный курс методологически, логически связан с основными социально-гуманитарными, философскими и теологическими дисциплинами. Это важнейший лингвистический курс, который должен занять достойное место в современном гуманитарном образовании.</p>
        <p>Кроме того, курс «Церковнославянский язык» представляет собой, по сути дела, славистическое введение в историю русского языка и культуры и играет важную роль в лингвистической и общефилологической подготовке.</p>
        <p><strong>Цель</strong> курса «Церковнославянский язык», который призван обеспечить слушателям возможность чтения и понимания текстов на церковнославянском языке и таким образом имеет по преимуществу практическую направленность,  состоит в следующем:</p>
        <ul>
            <li>показать важнейшие механизмы адекватного понимания текстов на церковнославянском языке;</li>
            <li>осветить ключевые проблемы церковнославянского языка;</li>
            <li>познакомить с языковым родством славянских народов и основами их книжной культуры;</li>
            <li>дать представление о главных, магистральных закономерностях, характеризовавших в ранние эпохи все славянские языки;</li>
            <li>проинформировать о разграничении таких понятий, как <i>праславянский</i>, <i>старославянский</i>, <i>церковнославянский</i>, <i>древнерусский</i>, <i>современный русский</i> языки, отметив, однако, их неразрывную связь;</li>
            <li>сформировать фактическую и методологическую базу для овладения элементами сравнительно-исторического анализа.</li>
            <li>Преподаватель в процессе изложения курса «Церковнославянский язык» должен решить следующие научно-теоретические и методические задачи:</li>
            <li>заложить основные теоретические сведения по церковнославянской грамматике;</li>
            <li>привить твердые навыки чтения разных видов;</li>
            <li>научить переводить и толковать богослужебные тексты;</li>
            <li>продемонстрировать основные алгоритмы грамматического и историко-лингвистического разборов текстов на церковнославянском языке;</li>
            <li>показать духовную и историко-культурную роль церковнославянского языка;</li>
            <li>укрепить в необходимости широкого распространения церковнославянской грамотности;</li>
            <li>указать на главные языковые отличия, которые характеризуют тексты разных жанров;</li>
            <li>наметить основные приемы самостоятельного составления разножанровых текстов на церковнославянском языке.</li>
        </ul>

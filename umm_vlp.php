        <h1>Введение в литургическое Предание</h1>
        <h2>Введение</h2>
        <p>Курс предназначен для учащихся факультета дополнительного образования ПСТГУ и разработан в соответствии с концепцией программы «Теология». Этот краткий курс в его очной форме читается по односеместровой  программе.  В курсе  унифицировано содержание учебного материала очной, заочной и дистанционной форм обучения. Предлагаемый курс должен способствовать ознакомлению слушателей с основным смыслом церковного богослужения, с содержанием церковных Таинств, их знакомству с историей формирования чинопоследования Таинств, а также хорошей ориентации в существующих на сегодняшний день чинопоследованиях Таинств. Курс имеет по преимуществу теоретическую направленность. Формы учебной работы с материалами предметного модуля должны обеспечить формирование первоначального навыка коллективного обсуждения богословских проблем.</p>
        <p><strong>Цель курса.</strong> Предметный модуль призван продемонстрировать слушателям феномен церковных Таинств, как глубинного содержания  внутренней церковной жизни соборного единства всей Церкви в целом и каждой отдельной личности в ней; также должен раскрыть органическое тождество современной церковной жизни Церкви и жизни Церкви апостольских времен.</p>
        <p><strong>Задачи курса</strong></p>
        <p>В ходе изучения курса должны быть выполнены следующие задачи. Слушатель должен получить:</p>
        <ul>
            <li>знание краткой истории формирования чинов православных Таинств;</li>
            <li>знакомство с чинопоследованием Таинств (по требнику, служебнику);</li>
            <li>знание христологических и пневматологических аспектов духовного содержания православных Таинств;</li>
            <li>понимание взаимосвязи учения о Таинствах и истории развития чинопоследований со Священным Писанием, с историей Церкви, ее догматическим и нравственным учением;</li>
            <li>краткое знакомство с богословским содержанием учения о Таинствах в католицизме и протестантизме;</li>
            <li>общее знакомство с современными особенностями и проблемами практики совершения Таинств.</li>
        </ul>

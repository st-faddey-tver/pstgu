Аттестация

Требования к уровню освоения курса

Слушатель, изучивший дисциплину должен:

знать хронологическую последовательность событий церковной истории до середины XV века и, прежде всего, даты, место проведения, повестку дня и решения Вселенских соборов; имена главнейших церковно-исторических деятелей и уметь охарактеризовать их роль в истории Церкви; основные вехи эволюции церковно-государственных отношений; иметь представление об основах церковного строя и церковного законодательства; иметь четкое представление о политических, канонических, литургических и догматических расхождениях между западным и восточным христианством к середине XI века.

уметь изложить содержание и охарактеризовать суть догматических движений и споров, указав на принципиальное отличие церковного взгляда на проблему от еретического;

обладать навыками пользования церковной терминологией и работы с источниками;

уметь давать консультацию по данному предмету в приложении к разным предметным областям с использованием специальной литературы.


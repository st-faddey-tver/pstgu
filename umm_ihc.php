        <h1>История христианской Церкви</h1>
        <h2>Введение</h2>

Изучение предметного модуля «История христианской Церкви» в составе программы профессиональной переподготовки «Теология» призвано дать слушателю общее знакомство с фактологией и хронологией церковной истории во взаимосвязи с историей формирования православного вероучения  (до падения Константинополя в 1453 г. - подробно, от события 1453 г.– обзорное знакомство).

Изучение истории христианской Церкви должно способствовать:

·         усвоению наиболее важных фактов древней церковной истории;

·         выяснению характера взаимоотношений древней Церкви с языческим и   христианским государством;

·         пониманию природы догматических движений и смысла вероучительных споров;

·         пониманию природы церковно-дисциплинарных споров и расколов;

·         ознакомлению с процессом кристаллизации догматических формулировок и основной  догматической терминологией;

·         ознакомлению с основами церковного законодательства и церковного управления;

·         выявлению расхождений между христианским Востоком и Западом, привешщих к разрыву между ними церковного общения;

·         пониманию причин гибели Византийской Империи.

Цель изучения данного предметного модуля: обеспечить понимание слушателем истории Церкви как земного бытия Тела Христова и наличие у слушателя общего представления об историческом происхождении современных реалий Православия.

Задачи, которые должны быть решены в процессе обучения:

·         дать хронологически последовательный очерк основных событий церковной истории до середины XI века;

·         охарактеризовать догматические движения первого тысячелетия и обосновать принципиальный характер догматических споров;

·         проследить эволюцию взаимоотношений Церкви и государства;

·         ознакомить с основания церковного строя и законодательства, проследить становление системы церковного управления;

·         определить факторы, приведение к разрыву церковного общения между                 Западом и Востоком;

·         выявить причины падения Византийской Империи и рассмотреть события, с ним связанные.


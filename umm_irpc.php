        <h1>История Русской Православной Церкви</h1>
        <h2>Введение</h2>
        <p>Курс предназначен для учащихся факультета дополнительного образования ПСТГУ и разработан в соответствии с концепцией программы «Теология». Этот краткий курс в его очной форме читается по одногодичной (двухсеместровой) программе. В предлагаемой программе унифицировано содержание учебного материала очной, заочной и дистанционной форм обучения. Курс носит обзорный характер. Предметный модуль призван познакомить слушателя с историей Русской Церкви. Обучение по модулю должно познакомить слушателей с фактологией и хронологией истории Русской Церкви, закономерностями ее процессов. Учащиеся должны составить общее представление о процессах в истории Русской Церкви, ее основных закономерностях, научиться анализировать источники и литературу. Обучение должно продемонстрировать взаимосвязь содержания курса с предметными модулями «История христианской Церкви», «Каноническое право», «Православное вероучение», а также другими дисциплинами науки «теология». Обучение должно продемонстрировать место и значение истории Русской Церкви в мировой истории. При изучении истории Русской Церкви слушателями курса предполагается знакомство с источниками и литературой.</p>
        <p><strong>Цель курса</strong> – сформировать у слушателя богословски корректный взгляд на историю Русской Церкви и дать знание основных исторических фактов, оказавших влияние на современное состояние Русской Православной Церкви.</p>
        <p><strong>Задачи курса</strong></p>
        <p>Обучение по курсу должно дать слушателю:</p>
        <ul>
            <li>знакомство с фактологией и хронологией истории Русской Православной Церкви (общий обзор ключевых моментов с более подробным изучением истории Русской Церкви в XIX – XX вв.);</li>
            <li>знакомство с процессами истории Русской Церкви в контексте истории Христианской Церкви и гражданской истории России;</li>
            <li>понимание закономерностей исторического процесса на примере истории Русской Церкви;</li>
            <li>умение работать с историческими источниками и литературой;</li>
            <li>умение объективно анализировать события истории Русской Церкви, как части истории Христианской Церкви и части всемирной истории;</li>
        </ul>      
        <p>Обучение должно продемонстрировать взаимосвязь содержания курса с предметными модулями «История христианской Церкви», «Каноническое право», «Православное вероучение» в области усвоения общих закономерностей исторического процесса.</p>

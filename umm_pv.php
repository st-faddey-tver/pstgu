        <h1>Православное вероучение</h1>
        <h2>Введение</h2>
        <p>Курс предназначен для учащихся факультета дополнительного образования ПСТГУ и разработан в соответствии с концепцией программы «Теология». Этот курс в его очной форме читается по одногодичной (двухсеместровой)  программе. В предлагаемой программе  унифицировано содержание учебного материала очной, заочной и дистанционной форм обучения. Курс должен способствовать ознакомлению слушателей с основным смыслом православного вероучения, с содержанием православных догматов, с историей их формулирования, с отличиями православного вероучения от еретических богословских концепций отпавших от Православия религиозных сообществ. Предмет должен способствовать успешному овладению специальной общепринятой богословской терминологией. Предмет «Православное вероучение» неразрывно связан с другими богословскими и церковно-историческими дисциплинами — в первую очередь такими как: «Священное Писание Ветхого Завета», «Священное Писание Нового Завета», «История христианской Церкви» и «Святоотеческая письменность»; он образует вместе с ними единую систему знаний и является структурирующей дисциплиной. Изучение православного вероучения направлено на формирование у слушателей основ догматического сознания. Формы учебной работы с материалами предметного модуля должны обеспечить формирование навыков реферирования богословских текстов.</p>
        <p><strong>Цель курса</strong> – изучение православного вероучения направлено на формирование у слушателей основ догматического сознания как основы подлинной православной духовности и церковной жизни.</p>
        <p><strong>Задачи курса</strong></p>
        <p>Обучение по предметному модулю «Православное вероучение» должно дать слушателю:</p>
        <ul>
            <li>представление о неразрывном единстве вероучительных положений Православия и подлинной духовной жизни христианина;</li>
            <li>систематическое знакомство с православными догматами, с содержанием догматического учения Православной Церкви;</li>
            <li>представление о содержании основных понятий и терминов православной догматической науки;</li>
            <li>навык интерпретации основных вероучительных положений, содержащихся в Никео-Константинопольском Символе веры и постановлениях Вселенских Соборов;</li>
            <li>хронологически последовательный очерк истории догматических движений от времен апостолов и до наших дней;</li>
            <li>знакомство с отдельными сторонами святоотеческого богословия;</li>
            <li>представление о характерных чертах различных богословских школ;</li>
            <li>знание основных древних ересей и их опровержений, понимание основных причин вероучительных отличий богословских систем христианских Востока и Запада;</li>
            <li>навык нахождения и анализа догматической составляющей в тексте;</li>
            <li>умение выявить наличие неправославных идей (противоречие православным догматам) в различных богословских текстах;</li>
            <li>понимание взаимосвязи православного вероучения со Священным Писанием, видение единства между существующим ныне православным догматическим учением и учением, содержащимся в Священном Писании Ветхого и Нового Завета;</li>
            <li>видение смысловой взаимосвязи между теологическими дисциплинами Православное вероучение, История Христианской Церкви и Святоотеческая письменность — как адекватное понимание характера их неразрывной взаимозависимости внутри комплекса предлагаемых к изучению богословских модулей;</li>
            <li>знакомство слушателям курса с основными тенденциями в современной догматической науке.</li>
        </ul>

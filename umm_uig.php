        <h3>Комментарий  к списку литературы</h3>
        <p>Основной литературой  для изучения курса является <strong>Учебное пособие «Богослужебный Устав и гимнография» Никулиной Е. Н.</strong>, составленное на основании приведенных в списке литературы учебников по литургике. В Учебном пособии собран и в краткой форме изложен практически весь необходимый материал. Это минимум, который рекомендуется освоить в первую очередь. Учебное пособие имеет ряд приложений, в которых представлены краткие схемы служб, тексты наиболее известных песнопений, фрагменты работ по литургике, необходимые при изучении курса.</p>
        <p>Следующая книга, на которую хотелось бы обратить внимание &ndash; это <strong>лекции М. С. Красовицкой</strong>. В этих лекциях представлен полный курс литургики в объеме программ для дневного, вечернего и заочного отделений ПСТГУ. При изучении нашего курса указанные лекции используются не полностью. Часть материалов, обязательных при изучении курса, приведена в Учебном пособии. К самим лекциям мы рекомендуем обращаться в самом начале изучения дисциплины, для введения в ее проблематику (лекции № 1 – 2), а также при изучении православных праздников (лекция № 11), богослужения Великого поста и Страстной Седмицы (лекции № 12 – 19). В лекциях М. С. Красовицкой разбирается не только структура служб, но и содержание песнопений. Поэтому для нашего курса эта работа является наиболее важной из всех учебных пособий, указанных в списке основной литературы к курсу.</p>
        <p>Работы архиеп. <strong>Аверкия (Таушева)</strong> и <strong>схиархим. Иоанна (Маслова)</strong> содержат подробное описание структуры православного богослужения в объеме требований Духовной Семинарии. Архиепископ Аверкий (ум. 1976) 24 года был ректором Свято-Троицкой Семинарии в США, преподавал Священное Писание, литургику, гомилетику. Схиархимандрит Иоанн Маслов (ум. 1991) читал лекции в Московской Духовной Семинарии. Эти учебники в нашем курсе рекомендуется использовать выборочно, в качестве справочного материала по отдельным вопросам.</p>
        <p>В <strong>«Литургике» проф. архим. Киприана Керна</strong> (ум. 1960) можно найти сведения о возникновения различных гимнографических жанров, формировании годового круга праздников и постов и других вопросах истории православного богослужения.</p>
        <p><strong>«Толковый Типикон» проф. М.Н. Скабаллановича</strong> – это  фундаментальный дореволюционный научный труд, посвященный истории формирования современного чина богослужения. Основательно изучить его, возможно, пожалуй, только серьезному специалисту. Но в нем есть одна глава, прочитать которую мы рекомендуем всем, изучающим наш курс. Она называется «Практическая осуществимость всего устава всенощной». В ней замечательно описано совершение идеального (то есть соответствующего всем требованиям Устава) Всенощного бдения, отслуженного в начале ХХ века в Киевской Духовной Академии. Главу эту желательно прочитать после изучения Всенощного бдения по учебному пособию и рекомендуемым книгам. (Эта глава включена в приложение к Учебному пособию).</p>
        <h2>Методические рекомендации</h2>
        <h3>Методические рекомендации по изучению модуля и организации самостоятельной работы</h3>
        <p>Для успешного освоения курса необходимо правильно организовать свой труд. Материал в курсе непростой, поэтому без собранности и добросовестной работы его освоить крайне сложно. При изучении курса рекомендуется придерживаться следующих правил.</p>
        <p>1. Не следует отвлекаться на дополнительное, пока не освоено основное. Практически весь нужный основной материал содержится в Учебном пособии. Это необходимо выучить в первую очередь. И только потом, если остается время, можно читать то, что прямого отношения к курсу не имеет. Перед чтением Учебного пособия полезно ознакомиться с содержанием учебных заданий по изучаемой теме.</p>
        <p>2. Еще одной распространенной ошибкой является перескакивание с задания на задание. Так делать нельзя, поскольку каждая тема в данном курсе является базисом для освоения следующей. Все темы нужно изучать по порядку, стараясь не доводить до того, чтобы из-за бессистемности накопился большой объем непонятого материала.</p>
        <p>3. Для успешного изучения курса необходимо регулярно посещать богослужение. Это настолько важное условие освоения материала, что без него наши занятия бессмысленны! Читая учебники, мы должны узнавать то, о чем в них говорится, а, участвуя в богослужении, вспоминать то, что изучали. Но самое главное — этот предмет нельзя постичь только умом, он призван осмыслить то, что уже является частью нашей духовной жизни. Нельзя изучать богослужение вне молитвенного общения с Богом.</p>
        <p>4. Задания по курсу соответствуют темам Учебного пособия. Перед каждым заданием указано, какую тему и какой раздел пособия нужно прочитать для его выполнения.</p>
        <p>5. Поскольку целью нашего курса является изучение как структуры богослужения, так и его содержания, то и задания, в основном, тоже будут двух типов. Одни направлены на заучивание необходимого минимума фактического материала, другие - на осмысление богословских идей песнопений. Для первых вполне достаточно объема учебного пособия, для вторых потребуется весь багаж богословских знаний, полученных на других курсах. Особенно часто придется обращаться к материалам курсов Православного вероучения, Священного Писания Ветхого и Нового Завета.</p>
        <p>6. Ответы должны представлять собой самостоятельное рассуждение на основе материалов темы, а не копии из Учебного пособия. Ответы-копии будут оценены как неудовлетворительные.</p>
        <p>7. Задания по анализу содержания богослужебных текстов делаются по следующему плану:</p>
        <p>1) Перевод текста.</p>
        <p>2) Тема (иногда в песнопении может быть несколько тем).</p>
        <p>3) Библейская тематика в песнопении.</p>
        <p>а) Ветхозаветные прообразы и пророчества.</p>
        <p>б) Сведения из Евангелия, книги Деяний  или указания на тексты из апостольских посланий.</p>
        <p>Необходимо назвать прообразы, пророчества или сведения из Нового Завета и пояснить, как они осмысляются гимнографом. В ответе должны быть указаны ссылки на Священное Писание.</p>
        <p>4) Отражение в песнопении сведений из Предания (если есть).</p>
        <p>5) Догматические положения (если есть). Нужно назвать догмат и пояснить, как он отражен в песнопении (каким словом, выражением и пр.).</p>
        <p>6) Художественные особенности текста (напр., противопоставления, сравнения, построение песнопения  в форме диалога и пр.).</p>
        <p>8. При полностью самостоятельном изучении курса (в рамках заочной формы обучения) рекомендуется следующий порядок работы:</p>
        <ul>
            <li>Изучить раздел Учебного пособия</li>
            <li>Проверить свои знания по вопросам для самопроверки</li>
            <li>Написать конспект билета к экзамену</li>
            <li>Выполнить задания контрольной работы, относящиеся к изученному разделу.</li>
        </ul>
        <p>9. При изучении курса в рамках вечерней формы обучения не следует ограничиваться прослушиванием лекций. После каждой лекции необходимо повторять пройденный материал по Учебному пособию и выполнять соответствующие  задания Контрольных работ.</p>
        <p>10. При изучении курса в дистанционной форме основной проблемой является отставание от учебного графика. Поэтому следует сразу же выработать собственный график работы и не откладывать на другое время то, что можно в настоящий момент.</p>
        <p>11.Самой сложной, по отзыву учащихся, является первая часть курса (особенно тема 2 «Воскресное и праздничное богослужение»), в которой содержатся базовые понятия литургики. При их усвоении материал второй части курса значительных затруднений вызывать не будет.</p>
        <p>12. Минимальный уровень требований по курсу, необходимый для  успешной аттестации, указан ниже в разделе «Аттестация». Этим списком удобно пользоваться при подготовке к экзамену, чтобы упорядочить свои знания и проверить, усвоено ли самое главное.</p>
        <h3>Методические рекомендации для преподавателя.</h3>
        <p>Настоящий курс не имеет своей целью подготовку священнослужителей, церковнослужителей или певцов, он ориентирован на мирян и призван способствовать восприятию ими богослужебной традиции Православия в целом. Поэтому основное внимание следует уделять не заучиванию уставных особенностей богослужения, а донесению до слушателей его смысла, разъяснению богословского содержания богослужебных песнопений, привитию навыка их самостоятельного анализа. При очной форме обучению занятия необходимо сопровождать прослушиванием звукозаписей изучаемых песнопений.</p>
        <p>Необходимый минимум уставных требований для положительной аттестации по курсу указан ниже, в разделе «Аттестация». На экзамене разрешается пользоваться схемами служб и богослужебными книгами.</p>
        <h2>Основные виды занятий, используемых при обучении, и их назначение</h2>
        <p><i>Лекции.</i> На лекциях используется репродуктивный метод обучения. Назначение лекций в курсе Устава и гимнографии:</p>
        <ul>
            <li>разъяснить наиболее сложные теоретические положения курса,</li>
            <li>познакомить с различными видами церковного пения (византийское, знаменное, партес, обиход), с наиболее известными песнопениями.</li>
            <li>дать ориентиры для дальнейшего самостоятельного изучения.</li>
        </ul>
        <p><i>Семинары.</i> Назначение семинаров  в курсе Устава и гимнографии — привить навык анализа богословского содержания богослужебного текста, актуализируя знания, полученные на других курсах (в первую очередь, на курсах Священного Писания Ветхого и Нового Завета и догматического богословия).</p>
        <p><i>Самостоятельные письменные работы</i> (контрольные работы, доклады). Назначение контрольных работ:</p>
        <ul>
            <li>проверить качество усвоения фактического материала,</li>
            <li>сформировать навык самостоятельного анализа богословского содержания богослужебных текстов,</li>
        </ul>
        <p>Назначение докладов — сформировать некоторые общие навыки самостоятельной научной работы:</p>
        <ul>
            <li>систематизация материала,</li>
            <li>последовательное письменное изложение отдельных богословских вопросов,</li>
            <li>правильное цитирование источников, грамотное оформление ссылок и библиографии.</li>
        </ul>
        <h2>Аттестация</h2>
        <h3>Содержание аттестации.</h3>
        <p>На аттестации поверяется знание материала курса в объеме программы.</p>
        <p>1. Основное внимание уделяется не столько знанию чинопоследований служб суточного круга, сколько умению их анализировать, выявлять особенности, характерные для определенного периода года.</p>
        <p>2. Обязательным условием успешной аттестации является умение разъяснить богословский смысл изученных песнопений.</p>
        <p>3. Тропари и кондаки Пасхи и двунадесятых праздников необходимо знать наизусть.</p>
        <h3>Способ проведения аттестации.</h3>
        <p>Аттестация для вечерней формы обучения:</p>
        <ul>
            <li>Промежуточная аттестация за первую и вторую части курса поводится по результатам аудиторных проверочных работ;</li>
            <li>Итоговая аттестация – в форме экзамена.</li>
        </ul>
        <p>Аттестация для заочной формы обучения проводится в  форме экзамена. Условием допуска к экзамену является положительная оценка за контрольную работу.</p>
        <p>Аттестация при дистанционной форме обучения осуществляется на  основании текущих оценок и результатов итогового тестирования.</p>
        <h3>Критерии оценивания.</h3>
        <p>Оценка «удовлетворительно» ставится в том случае, если уровень знаний слушателя не превышает объема минимальных требований к экзамену.</p>
        <p>Оценка «хорошо» ставиться в том случае, если слушатель рассказал материал билета с некоторыми недочетами, ответил на часть дополнительных вопросов.</p>
        <p>Оценка «отлично» ставиться, если слушатель продемонстрировал умение легко ориентироваться во всем материале курса, независимо от того, входит этот материал в его билет, или нет; ответил на все дополнительные вопросы.</p>

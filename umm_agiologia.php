        <h1>Агиология</h1>
        <h2>Введение</h2>
        <p>Курс предназначен для учащихся факультета дополнительного образования ПСТГУ, разработан в соответствии с концепцией программы «Теология» и является дополнением к основным богословским дисциплинам (Священному Писанию Ветхого и Нового Завета, истории Церкви, патрологии, догматическому и нравственному богословию, каноническому праву и др.), материал которых обобщен в контексте понятия святости. В курсе унифицировано содержание учебного материала очной, заочной и дистанционной форм обучения.</p>
        <p><strong>Цель курса</strong> – сформировать у слушателей представление о различных  путях к святости и духовных особенностях каждого вида подвига в национальном, географическом  и историческом аспектах.</p>
        <p><strong>Задачи курса:</strong></p>
        <ul>
            <li>разъяснить основы православного подхода к почитанию святых и их канонизации;</li>
            <li>выявить особенности каждого вида подвига;</li>
            <li>ознакомить с наиболее значительными памятниками агиографической литературы;</li>
            <li>проследить духовную преемственность и взаимовлияние различных видов подвига.</li>
        </ul>
        <h2>Тематическое содержание предметного модуля</h2>
        <ol>
            <li>Вводные понятия.</li>
            <li>Апостолы и равноапостольные.</li>
            <li>Мученики.</li>

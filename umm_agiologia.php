        <h2>Тема 1. Вводные понятия.</h2>
        <p>Понятие святости в Ветхом и Новом Завете. Святость и обожение. Принадлежность к Церкви как условие подлинной святости. Почитание святых, необходимость молитв святым. Причины отказа от молитвенного призывания святых в протестантизме. Основания для почитания святых мощей; нетление мощей. Чествование святых мощей в Православии.</p>
        <p>Многообразие путей к святости. Краткие сведения о содержании подвига апостолов, мучеников, исповедников, страстотерпцев, святителей, преподобных, благоверных, юродивых, праведных. Общий путь к святости ─ путь креста.</p>
        <p>Канонизация. Критерии канонизации в Православии и Римской Церкви; основные исторические этапы канонизации во Вселенской Церкви и в Русской Православной Церкви, их особенности.</p>
        <p>Агиографические памятники. Крупнейшие собрания житий святых: свод житий св. Симеона Метафраста, Великие Четьи Минеи митр. Макария, Чудовские, Тулуповские, Милютинские Минеи, Четьи Минеи свт. Дмитрия Ростовского, свт. Филарета (Гумилевского) и др. Значение богослужебных Миней для агиологии. Месяцесловы, святцы, прологи, патерики. «Святые о святых»: агиографические сочинения свт. Афанасия Александрийского, свт. Григория Турского, бл. Феодорита Кирского, св. Григория Двоеслова и др.</p>
        <p>Назначение жития. Житийный канон в византийской и древнерусской агиографии. Связь жития с литургической жизнью Церкви. Изменение формы и содержания жития в XIX-XX веках. Проблемы современной агиографии.</p>

        <h2>Тема 4. Преподобные.</h2>
        <p>Содержание подвига преподобных. Аскетизм как непременное условие подлинно христианской жизни каждого члена Церкви. Богоустановленность подвига преподобных. Составляющие телесного и душевного делания инока. Формы монашеского жительства: общежитие, скитское житие, отшельничество. Затворничество и столпничество. Обители неусыпающих. Связь подвига преподобных с мученичеством. Изображение подвига преподобных в гимнографии.</p>
        <p>Историко-географический обзор подвига преподобных. Возникновение монашества. Характерные черты древнего подвижничества в разных регионах Востока (Египет, Сирия, Палестина и др.). Распространение идеалов восточного монашества на Западе. Крупнейшие монашеские центры и наиболее известные святые подвижники Востока и Запада. Афон: зарождение монашеской жизни на Афоне, наиболее известные подвижники. Исихазм, его сущность и представители. Исихазм в сочинениях прп. Григория Синаита и свт. Григория Паламы. Прп. Никодим Святогорец и «Добротолюбие».</p>
        <p>Основные этапы монашеского подвижничества на Руси. Домонгольский период (X-XIII вв.), подвижники Киево-Печерской Лавры. Исихазм на Руси. Прп. Сергий Радонежский и расцвет монашества в XIV-XVI вв., северная и южная ветви последователей прп. Сергия (Северная Фиваида и подмосковные монастыри). Упадок монашеского подвига в XVIII веке. Г. Федотов о «трагедии древнерусской святости». Возрождение монашества в конце XVIII - XIX вв. Преподобные ХХ века. Особенности монашеского подвига на каждом этапе.</p>
        <p>Старчество. Зарождение старчества и его роль в древнем иночестве. Тема старчества в памятниках христианской письменности. Связь старчества и духовничества. Старческий подвиг на Руси: старчество в домонгольский период (X-XIII вв.), времена преподобного Сергия, его учеников и последователей (XIV-XVI вв.), восстановление традиций старчества прп. Паисием Величковским (XVIII в.), Оптинские старцы (XIX в.), старчество в ХХ веке. Призвание на старческое служение и подготовка к нему. Содержание старческого служения; благодатные дарования, необходимые для этого подвига. Трудности и опасности старческого окормления.</p>

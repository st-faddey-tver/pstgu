        <h2>Тема 3. Мученики.</h2>
        <p>Содержание мученического подвига. Богоустановленность подвига. Христос — Первый Мученик. Мученичество как продолжение апостольского служения, жертвенный характер мученичества, связь мученичества с покаянием. Крещение кровью. Богослужебные тексты о мученическом подвиге. Тема мученичества в святоотеческий письменности III-IV вв. (сщмч. Киприан Карфагенский, свт. Иоанн Златоуст, свт. Василий Великий). Мученический аспект каждого пути к святости.</p>
        <p>Очерк истории гонений на христиан. Ветхозаветные мученики. Мученичество в Римской империи до Миланского эдикта. Мученики, пострадавшие от императоров-еретиков (монофилитов, иконоборцев). Мученический подвиг в различных регионах мира в IV-XX вв.: Аравия, Персия, Афон, Балканы, Китай, Грузия. Мученический подвиг на Руси до ХХ века: мученики от язычников до крещения Руси, от язычников во время миссионерских трудов, страстотерпцы, убиенные дети, исповеднический подвиг русских святителей, мученики от мусульман. Мученический подвиг в ХХ веке. Особенности гонений на христиан в советской России по сравнению с гонениями в Римской империи.</p>
        <p>Различные формы мученического подвига (виды страданий, послужившие основанием для канонизации). Исповедники. Страстотерпцы.</p>

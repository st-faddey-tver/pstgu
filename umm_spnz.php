Комментарий  к  Библиографии курса

Основным пособием при  изучении обеих частей курса является  «Руководство к изучению книг Священного Писания Нового Завета», составленное Ивановым А. И. (1837 – 1912) для духовных семинарий. Пособие представляет собой богословский и исторический комментарий ко всем новозаветным книгам, позволяющий познакомиться с их содержанием и создающий основу для  самостоятельного изучения Нового Завета. Автор обращает особенное внимание на догматические и нравственные аспекты новозаветного учения, на трудные для понимания места, дает при необходимости исторические справки, предлагает корректные версии согласования повествований евангелистов.  Несмотря на время выхода этой книги в свет, стиль изложения ее понятен современному читателю.

При изучении Четвероевангелия нужно обратить внимание на относительно недавно изданную в Симферополе книгу «Господские праздники» известного греческого богослова, митрополита Иерофея (Влахоса) (род. в 1945 г.).  Изложение  представляет прекрасный пример богословского синтеза: автор рассматривает евангельские события сквозь призму догматического, литургического  и нравственного богословия Православной Церкви.

Из корпуса святоотеческих толкований на Евангелие наиболее значимы при изучении первой части курса Беседы  свт. Иоанна Златоуста (IV в.) на Евангелие от Иоанна. Составленное в жанре беседы  (проповеди) толкование полезно в методическом отношении, показывая пример экзегетического анализа библейского текста и извлечения смысла священных текстов (рекомендуется обращение к этим  толкованиям при изучении догматических бесед Евангелия от Иоанна).  Беседы свт. Иоанна Златоуста способствуют появлению навыка нравственной рефлексии:  критического анализа  своей жизни  в свете Писания.   

Для тех, кто не имеет возможности  уделить достаточно времени чтению творений свт. Иоанна (а они довольно обширны), рекомендуем обратиться к толкованиям блаж. Феофилакта Болгарского (XI в.), составившего на основе  бесед  Златоуста  и других святоотеческих толкований краткие толкования на все четыре Евангелия, на каждый стих. Толкования блаж. Феофилакта будут полезны и при работе с апостольским корпусом.

«Евангельская история», составленная свт. Феофаном Затворником (1815-1891), русским православным подвижником, духовным писателем и экзегетом, состоит из двух частей. Первая,  «Евангельская история о Боге Сыне, воплотившемся нашего ради спасения», представляет собой пересказ евангельской истории. Вторая часть, «О последовательности евангельских событий. Историко-богословское исследование» описывает хронологическую последовательность евангельских событий и дает комментарии на некоторые трудные для понимания фрагменты евангельского повествования.

Среди учебных пособий по Новому Завету для высших духовных учебных заведений можно назвать учебник профессора кафедры Библеистики Свято-Сергиевского института в Париже еп. Кассиана (Безобразова) (1892-1965) «Христос и первое христианское поколение». В этом труде доминирует научный и системный подход. При обозначении проблем, связанных с исследованием библейского текста, автор опирается на достижения библейской науки 40-х гг. ХХ в.; согласовывая материал четырех Евангелий, он приводит в определенную систему и концепцию евангельское повествование, но эти характеристики могут быть в равной мере отнесены как к достоинствам, так и к несовершенствам этого труда. Авторское видение евангельской истории небесспорно и нередко находится вне русла церковного Предания. В комментариях на апостольский корпус еп. Кассиан дает описание проблемы авторства и анализирует содержание каждой книги, помогает увидеть логику тематического развития внутри  посланий, а также тематические связи посланий. Автор стилистически изящно, но, к сожалению, не всегда ясно выражает учение апостолов, допуская некоторые некорректные  определения.

Учебное пособие по Новому Завету преподавателя Санкт-Петербургской академии прот. Александра Сорокина «Христос и Церковь в Новом Завете» вышло относительно недавно – в 2005 г. В основу этой книги положен курс лекций о. Александра по Введению в Новый Завет. Несмотря на намерение автора создать систематическое пособие, в котором были бы равно учтены достижения современной библеистики и церковное Предание, его труд учитывает преимущественно первое. Автор опирается на работы русских и западных богословов, в том числе католических и протестантских, исследования и выводы которых автор счел убедительными. Интерпретация священных текстов в свете Предания в работе почти не представлена; несмотря на то, что автор проявил заботу о выявлении связи Писания и богослужения как формы Предания, позволяющей изъяснить смысл  многих новозаветных текстов, на святоотеческие труды исследователь не опирается.

 

Помощь в получении необходимых при чтении и толковании текста исторических сведений и справок, истории ветхозаветных праздников и обычаев, при изучении географии и хронологии евангельских и ветхозаветных событий может оказать Библейская энциклопедия Брокгауза. При работе с этим словарем нужно учесть, что составлен он был учеными-протестантами и в некоторых его статьях приводятся мнения и объяснения, противоречащие церковному Преданию и догматическому учению Православной Церкви.

«Евангельский синопсис», составленный заведующим кафедрой библеистики ПСТГУ, прот. Алексеем Емельяновым, дает представление о последовательности евангельских событий, а также помогает работе с параллельными местами евангельского повествования.

Двухтомник Барсова М.В. «Сборник статей по истолковательному и назидательному чтению Четвероевангелия»,  указанный в разделе дополнительной  литературы, представляет собой подборку толкований святых отцов и комментариев дореволюционных  русских богословов на все евангельские события и беседы. Автор не ограничивается одним комментарием на отдельные события, а приводит спектр мнений и толкований по каждому вопросу.  В списке дополнительной литературы ко второй части курса размещен аналогичный сборник этого же автора – по книге Деяний святых апостолов.

При изучении последней темы первой части курса (о событии Воскресения) следует обратить внимание на исследование Веселина Кесича «Первый день нового творения. Воскресения и христианская вера». Автор, основываясь на Священном Писании и Предании, разносторонне рассматривает вопрос о Воскресении Господа Иисуса Христа. В работе приводятся мнения и современных экзегетов протестантского и либерального толка; автор всегда отмечает, когда их суждения и выводы расходятся с православным пониманием жизни, смерти и воскресения Христа. 

При изучении второй части курса (Апостол) рекомендуется привлечение толкований свт. Феофана Затворника на послания ап. Павла. В силу большого объема этих толкований в Библиографии к курсу предложен краткий комментарий к посланиям, составленный свящ. Николаем Рудинским на основе толкований свт. Феофана (книга «Жизнь и труды святого апостола Павла»).

 

 

Методические рекомендации  

 

Методические рекомендации по изучению модуля и организации самостоятельной работы

Одна из особенностей изучения курса Священного Писания Нового Завета состоит в невозможности ограничиться только каким-то одним учебным пособием или толкованием.  Освоение курса требует большой собирательной работы и привлечения различных материалов.

При этом нужно помнить, что основным источником знаний и одновременно предметом изучения на курсе является само Священное Писание.  Нередко возникает опасность подмены: какие-либо пособия (напр., пособие еп. Кассиана (Безобразова)),  в силу живости или оригинальности богословской мысли и языка становятся «властительницами умов», так что сама евангельская история несколько уходит на второй план под давлением  нарочитой системности идей автора.  

Вполне естественно, что в Писании и после изучения этого курса останутся неясные места. Как сказал свт. Феофан Затворник, составивший «Евангельскую историю о Боге Слове» и толкования ко всем посланиям ап. Павла: «Да, ведь, с одним Евангелием или Новым Заветом можно целый век прожить, и все читать. Все его читать и до конца не дочитаешь. Сто раз прочитай, а там все будет оставаться недочитанное…»

Первым помощником для понимания смысла Писания должны быть святоотеческие толкования. Различные научные теории  и изыскания исследователей-библеистов могут быть лишь подспорьем, к тому же святоотеческая экгегеза и библеистика редко находят общий язык.  

Святитель Филарет (Дроздов), известный русский богослов, выделял следующие этапы в постижении смысла Писания:

а) рассмотрение изучаемого события или текста в пространстве Священного Писания: в евангельском контексте, в отношении к книгам Ветхого Завета или апостольского корпуса, в которых данная тема рассматривается или имеет прямые параллели;

б) затем  – обращение к греческому тексту новозаветного текста: часто смысл фраз зависит от значения одного слова, и толкователи никогда не пренебрегали обращением к языку оригинала. (Очевидно, что это не общедоступный этап, в рамках данного курса он может быть предложен только как желательный, но необязательный. Но при наличии интереса к этой форме работы со священным текстом можно предложить использовать комментарии к греческому тексту на отдельные священные книги, их в настоящее время издано много; есть подобный разбор отдельных слов и фраз и в писаниях святых отцов – обратите на это внимание);

в) следующий этап: обращение к святоотеческим толкованиям и затем – к современным исследованиям и комментариям.

Толкования отцов древней Церкви и авторов, живших в средние века, для современного читателя часто сами нуждаются в толковании: не всегда адекватно воспринимается даже понятийный аппарат их писаний. При чтении толкований, при изучении программы и подготовке ответов на контрольные вопросы, обязательно надо стараться своими словами выразить святоотеческую мысль. Пока это не будет сделано, усвоения мысли читающим не произойдет.

 

Особенный акцент надо сделать на достижение хорошего знания священного текста. Это не формальное требование. Полноценное освоение курса невозможно без умения свободно ориентироваться в тексте Нового Завета. Этого навыка нельзя достичь только ответами на контрольные вопросы, участием в обсуждениях и поиском цитат в электронной Библии. Это самостоятельный и «невидимый миру» труд регулярного и внимательного чтения Писания. Но труд благодарный. Когда мы работаем со святоотеческими толкованиями, привлекает внимание та свобода, с которой память и ум толкователей обращается к любой книге, главе и стиху.  Да и один из основных методов толкования Библии – толкование Писания через само Писание – обязывает изучающего хорошо знать священный текст.

Возможны  различные варианты организации самостоятельной работы. Изучение Евангелия и апостольского корпуса по методике несколько отличается, так как и тематический принцип организации обеих частей курса отличен. Первая часть курса не изучает Евангелия как отдельные книги, а рассматривает евангельское повествование как единую событийную канву, составленную на материале всех четырех Евангелий; книги же апостольского корпуса изучаются по отдельности, хотя и с выявлением тематической взаимосвязи между ними.  Вторая часть курса, возможно, покажется более тяжелой и потребует больших усилий, чем первая, поскольку с содержанием апостольского корпуса слушатели, как правило, знакомы меньше, чем с евангельской историей. Вот один из продуктивных порядков самостоятельной работы с текстом  апостольских посланий:

1)             первое чтение послания;

2)             если это послание ап. Павла: повторное чтение текста, но уже с использованием подробного плана послания, составленного свт. Феофаном Затворником;

3)             самостоятельное составление краткого плана послания;

4)             выделение трудных для понимания фрагментов или тем;

5)             выявление в тексте тем, имеющих параллели в ранее прочитанных посланиях;

6)             знакомство с описанием послания в рекомендуемом «Руководстве для изучения…» Иванова А.И.

7)             объяснение трудных фрагментов текста с помощью толкования свт. Феофана Затворника или блаж. Феофилакта Болгарского;

8)             сопоставления толкований, отличных по способу (напр., буквального и аллегорического во всех его подвидах), выявление различных смысловых пластов текста.

Постижению смысла священного текста также способствует:

·                  чтение книг апостольского корпуса не только на русском языке, но и на церковнославянском (часто этот язык, являющийся калькой с греческого, помогает точнее понять мысль апостолов);

·                  выявление во время богослужений связи читаемых апостольских и евангельских чтений с праздничной темой дня.

 

Основные виды занятий, используемые при обучении, и их назначение

 

1.           Лекции.

2.           Семинары.

Это два основных вида аудиторных занятий на заочном и вечернем отделении. На лекции дается систематическое изложение основного материала по курсу, обращается внимание учащихся на ключевые моменты в каждой теме, даются общие установки и ориентиры для изучения Писания. Многообразие литературы, с одной стороны, и отсутствие учебных пособий, излагающих материал корректно, систематически и в полном соответствии с Преданием Церкви, с другой, делает лекционный вид занятий обязательным.

Основное назначение семинаров – привитие навыка аналитического чтения Писания. Этому способствует  совместный (педагог и слушатели) анализ священных текстов, разбор трудных для толкования фрагментов. На семинаре проходит групповое обсуждение богословских вопросов и проблемных ситуаций, текстов, содержащих неточности богословского характера, тестов, содержащих многовариантные решения вопросов и т.д. Все это позволяет глубже освоить тему, закрепить знания, увидеть различные варианты решения проблемы, освоить культуру богословской дискуссии.

Для лучшего усвоения материала на лекции и семинаре обязательным является предварительное чтение изучаемых текстов Писания, а также самостоятельное изучение слушателями новых материалов в соответствии с программой. На лекции осуществляется лишь систематизация и дополнение самостоятельно полученной слушателями информации.

Для повышения активности и заинтересованности аудитории практикуется проведение лекции-беседы и совмещение лекции и семинара: изложение педагогом нового материала сочетается с групповым обсуждением отдельных аспектов изучаемой темы.

На дистанционной форме обучения лекции заменяются точно выверенным списком литературы и при необходимости – конспектом или комментариями преподавателя.

 

3.           Самостоятельная работа.

Ход самостоятельной работы слушателя определяется программой курса, содержащей вопросы для самопроверки к каждой теме, и различными видами контрольных заданий:

·         для заочной формы обучения: контрольной работой, содержащей разные типы заданий по тексту Писания и литературе к курсу;

·         для вечерней формы обучения: подготовкой индивидуальных докладов, реферированием богословских текстов, составлением таблиц и схем, разработкой тестов, богословской редакцией текстов, подготовкой письменных ответов на контрольные вопросы к занятию; 

·         для дистанционной формы обучения: подготовкой индивидуальных и групповых докладов, прохождением тестирования в режиме репетитора, разработкой тестов, подготовкой письменных ответов на контрольные вопросы к занятию.

Самостоятельная работа направлена на основательное изучение теоретической базы курса и активизацию работы с источниками (Священным Писанием и святоотеческими толкованиями).

 

Аттестация

 

Содержание аттестации.

На аттестации проверяется знание материала курса в объеме программы.

Экзаменационные требования к уровню знания новозаветного текста: 

·                  знать изложенные в Четвероевангелии события и поучения;

·                  иметь представление о плане Евангелий от Матфея и Иоанна и книги Деяний свв. апостолов;

·                  знать тематическое содержание апостольских посланий и догматических бесед Евангелия от Иоанна;

·                  уметь изложить евангельскую тему или тему апостольских посланий близко к тексту.

На экзамене не разрешается пользоваться библейским текстом.

 

Способ проведения аттестации.

Аттестация для заочной и вечерней формы обучения проводится в  форме устного экзамена. Условием допуска к экзамену слушателей обеих форм является положительная оценка за контрольную работу.

При аттестации слушателей дистанционной формы обучения учитываются следующие показатели: средний балл оценок за отдельные темы и наличие зачетов за тесты.

 

Критерии оценивания.

Общие требования к ответам на экзамене:

·         точное соответствие вопросу и полнота ответа,

·         аргументированность, обоснованность ключевых положений ответа,

·         знание опорных текстов Писания (близко к тексту).

На «отлично» оценивается ответ слушателя, исчерпывающе раскрывшего содержание билета, показавшего хорошее знание текста Писания и умение свободно в нем ориентироваться, ответившего на все дополнительные вопросы. 

На «хорошо» оценивается ответ слушателя, верно раскрывшего содержание билета и показавшего хорошее знание текста Писания, но оставившего без внимания те или иные второстепенные аспекты вопроса, допустившего незначительные фактические ошибки, не давшего верный ответ на дополнительные вопросы.  

«Удовлетворительно» оценивается ответ неполный (напр., если верно освещен только один вопрос билета), непоследовательный в изложении, допускающий фактические неточности, демонстрирующий поверхностное знание текста Писания.

«Неудовлетворительно» оценивается ответ слушателя, не раскрывшего содержание обоих вопросов билета, допустившего значительные фактические неточности или богословские ошибки.

 


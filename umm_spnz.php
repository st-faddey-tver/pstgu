        <h2>Введение</h2>
        <p><strong>Общее описание модуля.</strong></p>
        <p>Курс предназначен для слушателей Факультета дополнительного образования ПСТГУ и  разработан в соответствии с концепцией программы  профессиональной переподготовки «Теология». Курс Священного Писания Нового Завета, изучаемый на Факультете дополнительного образования, отличается от аналогичного курса, разработанного на Богословском факультете ПСТГУ, не являясь научно-ориентированным. При раскрытии исторических и экзегетических проблем он знакомит слушателей с некоторыми мнениями (в том числе спорными или несоответствующими Преданию Церкви) и достижениями библеистики (XIX-ХХI вв.), но не ориентирован на их систематическое рассмотрение и привлечение.</p>
        <p>Данный курс направлен на постижение слушателями места Нового Завета в православном Предании, в его взаимосвязи с Ветхим Заветом, экзегетической и литургической традицией. Обучение должно помочь выявлению ценностной системы Священного Писания и продемонстрировать возможности ее использования в качестве основы для анализа и оценки явлений личной и общественной жизни.</p>
        <p>Тематическая последовательность первой части курса (Четвероевангелия) задана единой событийной канвой евангельской истории, составленной на основе материала всех Евангелий.  Наиболее подробно данный курс рассматривает содержание Евангелия от Иоанна: во-первых, в силу того, что оно традиционно представляет наибольшую сложность для понимания,  во-вторых, потому что оно, как ни одно другое Евангелие, открывает догматический и духовно-нравственный смысл евангельских событий и учения.</p>
        <p>Вторая часть курса представляет собой последовательное изучение книг апостольского корпуса: вначале исторической книги Деяний святых апостолов, затем посланий апостола Павла (в хронологическом порядке) и, наконец, Соборных посланий и Откровения ап. Иоанна Богослова. При изучении посланий обращается внимание на исторический контекст их появления; особое внимание уделено тематическим связям между посланиями.</p>
        <p><strong>Цель курса</strong> – познакомить слушателей с содержанием новозаветных текстов и способствовать появлению навыка самостоятельного изучения Писания Нового Завета в соответствии со Священным Преданием.</p>
        <p><strong>Задачи курса:</strong></p>
        <ul>
            <li>охарактеризовать общие и индивидуальные особенности новозаветных книг;</li>
            <li>показать соотношение и взаимосвязь ветхозаветного и новозаветного Откровения, а также новозаветного учения с другими областями богословского знания;</li>
            <li>привить навык толкования новозаветных текстов в свете Свящ. Предания (святоотеческая экзегеза, богослужебное предание и др.);</li>
            <li>научить свободно ориентироваться в новозаветном тексте;</li>
            <li>научить применять методы работы с библейским текстом, согласные с православной экзегетической традицией;</li>
            <li>кратко познакомить с критическими подходами к толкованию библейского текста и базовыми понятиями библеистики, раскрыть апологетическое значение этих знаний;</li>
            <li>научить слушателей самостоятельно формулировать догматические и нравственные проблемы, поставляемые новозаветным текстом.</li>
        </ul>
